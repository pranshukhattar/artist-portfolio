// Extracts only the icons the site uses into src/components/ui/icon-data.ts
// so the full Iconify sets never reach the client bundle.
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { getIconData, iconToSVG } from "@iconify/utils";

const load = (set) =>
  JSON.parse(readFileSync(new URL(`../node_modules/@iconify-json/${set}/icons.json`, import.meta.url)));

const ICONS = {
  // Interface — Solar
  play: ["solar", "play-bold"],
  pause: ["solar", "pause-bold"],
  prev: ["solar", "skip-previous-bold"],
  next: ["solar", "skip-next-bold"],
  arrowRight: ["solar", "arrow-right-linear"],
  arrowLeft: ["solar", "arrow-left-linear"],
  arrowUpRight: ["solar", "arrow-right-up-linear"],
  menu: ["solar", "hamburger-menu-linear"],
  close: ["solar", "close-square-linear"],
  volume: ["solar", "volume-loud-linear"],
  mute: ["solar", "volume-cross-linear"],
  chevronUp: ["solar", "alt-arrow-up-linear"],
  chevronDown: ["solar", "alt-arrow-down-linear"],
  home: ["solar", "home-2-linear"],
  music: ["solar", "music-note-2-linear"],
  calendar: ["solar", "calendar-linear"],
  user: ["solar", "user-linear"],
  // Platforms — Simple Icons (real marks, used only as links to the artist's profiles)
  instagram: ["simple-icons", "instagram"],
  youtube: ["simple-icons", "youtube"],
  spotify: ["simple-icons", "spotify"],
  tiktok: ["simple-icons", "tiktok"],
  soundcloud: ["simple-icons", "soundcloud"],
  appleMusic: ["simple-icons", "applemusic"],
};

const sets = {};
const out = {};
for (const [key, [set, name]] of Object.entries(ICONS)) {
  sets[set] ??= load(set);
  const data = getIconData(sets[set], name);
  if (!data) throw new Error(`Missing icon ${set}:${name}`);
  const { attributes, body } = iconToSVG(data);
  out[key] = { viewBox: attributes.viewBox, body };
}

writeFileSync(
  new URL("../src/components/ui/icon-data.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs — do not edit.\n` +
    `// Interface icons: Solar (CC BY 4.0). Platform marks: Simple Icons (CC0).\n` +
    `export const iconData = ${JSON.stringify(out, null, 2)} as const;\n\n` +
    `export type IconName = keyof typeof iconData;\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons`);
